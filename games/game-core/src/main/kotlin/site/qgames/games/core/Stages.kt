package site.qgames.games.core

/**
 * Стадии партии (`state.stage`). Стадия — самостоятельный кусок партии со своей механикой ходов, очерёдностью и часами;
 * список игроков общий на всю партию. Стадиями управляет сама игра: код текущей стадии лежит в состоянии, игра по нему
 * выбирает правила хода, а переход выдаёт в [GameRules.decide] или [GameRules.onTimeout] событием [changed].
 *
 * Переход заменяет состояние целиком (`stage-changed` = `PUT ["state"]`): новая стадия, поля игры и игроков, очерёдность;
 * часов нет, итога нет, варианты ходов пусты. Платформа следом сама ставит часы новой стадии (`timer-started`,
 * [GameRules.timer]) и варианты ходов (`move-options-changed`). Прошлые стадии остаются только в журнале. У игры из
 * одной стадии она одна — [PLAY].
 */
object Stages {

    /** Стадия партии сменилась: `PUT ["state"]` с состоянием новой стадии. */
    const val STAGE_CHANGED = "stage-changed"

    /** Ключ блока в состоянии. */
    const val STAGE = "stage"

    /** Основная стадия: у игр из одной стадии — единственная. */
    const val PLAY = "play"

    /**
     * Переход к стадии [start] (GameStart.stage): платформа превращает его в `PUT ["state"]` полного состояния стадии.
     * В одном наборе событий — не больше одного перехода и не вместе с концом партии; переход — последнее событие игры.
     */
    fun changed(start: GameStart<*>): SessionEvent = SessionEvents.put(STAGE_CHANGED, SessionEvents.path(SessionEvents.STATE), start)
}
